package edu.boun.edgecloudsim.edge_client;

import org.cloudbus.cloudsim.UtilizationModel;
import org.cloudbus.cloudsim.DatacenterBroker;

import edu.boun.edgecloudsim.utils.EdgeTask;
import edu.boun.edgecloudsim.utils.TaskProperty;

/**
 * =========================================================
 * MobileDeviceManager
 * =========================================================
 *
 * Extends CloudSim's DatacenterBroker to handle
 * task submission and orchestration for mobile
 * devices in edge computing scenarios.
 *
 * This class is responsible for:
 *
 * - task creation
 * - task submission
 * - offline-first behavior
 * - HES orchestration
 * - edge/cloud continuation
 * - synchronization control
 *
 */
public abstract class MobileDeviceManager
	extends DatacenterBroker {

	/*
	 * =========================================================
	 * Constructor
	 * =========================================================
	 */

	/**
	 * Constructor for MobileDeviceManager.
	 * Initializes the global broker for managing
	 * mobile device tasks.
	 *
	 * @throws Exception if broker initialization fails
	 */
	public MobileDeviceManager() throws Exception {

		super("Global_Broker");
	}

	/*
	 * =========================================================
	 * Initialization
	 * =========================================================
	 */

	/**
	 * Initializes the mobile device manager
	 * with required configurations.
	 *
	 * Called before starting task submission
	 * and management operations.
	 */
	public abstract void initialize();

	/*
	 * =========================================================
	 * CPU Utilization Model
	 * =========================================================
	 */

	/**
	 * Provides the CPU utilization model for tasks.
	 *
	 * Defines how CPU resources are utilized
	 * during task execution.
	 *
	 * @return UtilizationModel instance for CPU modeling
	 */
	public abstract UtilizationModel
		getCpuUtilizationModel();

	/*
	 * =========================================================
	 * Initial Task Submission
	 * =========================================================
	 */

	/**
	 * Submits a task generated by a mobile device.
	 *
	 * Responsible for:
	 * - creating EdgeTask
	 * - invoking orchestrator
	 * - initiating HES pipeline
	 *
	 * @param edgeTask task properties and requirements
	 */
	public abstract void
		submitTask(TaskProperty edgeTask);

	/*
	 * =========================================================
	 * HES Continuation
	 * =========================================================
	 */

	/**
	 * Continues the HES pipeline after EDGE execution.
	 *
	 * This method is responsible for forwarding
	 * tasks from EDGE to CLOUD.
	 *
	 * MOBILE -> EDGE -> CLOUD
	 *
	 * @param task EdgeTask already processed at EDGE
	 */
	public abstract void
		submitTaskToCloud(EdgeTask task);

	/*
	 * =========================================================
	 * Offline Queue
	 * =========================================================
	 */

	/**
	 * Stores task locally while device is offline.
	 *
	 * Used by:
	 * - OFFLINE_DIRECT
	 * - HES
	 *
	 * @param task task to be temporarily stored
	 */
	public abstract void
		storeLocally(EdgeTask task);

	/*
	 * =========================================================
	 * Synchronization
	 * =========================================================
	 */

	/**
	 * Flushes locally stored tasks when
	 * connectivity becomes available.
	 *
	 * Implements opportunistic synchronization.
	 */
	public abstract void
		synchronizeOfflineTasks();

	/*
	 * =========================================================
	 * Metrics Support
	 * =========================================================
	 */

	/**
	 * Updates synchronization metrics.
	 *
	 * Used for:
	 * - sync delay
	 * - offline duration
	 * - queue waiting time
	 *
	 * @param task synchronized task
	 */
	public abstract void
		updateTaskMetrics(EdgeTask task);
}